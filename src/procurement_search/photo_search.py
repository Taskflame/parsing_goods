"""Поиск по фото — ИЗОЛИРОВАННЫЙ модуль (никак не влияет на существующий
пайплайн поиска).

Сценарий байера: загрузить фото товара/детали/этикетки -> мультимодальная
модель qwen3.6-35b-a3b (доступна в синхронном AI Studio, базовый инстанс)
описывает объект и выдаёт поисковое ядро -> классический поиск товара.

ВАЖНО про форм-фактор: надписи на фото бывают далеко не всегда. Поэтому
модель НЕ ограничивается распознаванием текста, а описывает сам объект по
внешнему виду (форма, материал, конструкция, назначение), а также читает
текст, если он есть. Это устойчиво к реальным фото без подписей.

Формат передачи картинки: как у всех мультимодальных моделей OpenAI-совместимо
— image_url с data-URI base64 (проверено живым вызовом: модель отвечает
описанием). Ответ — строгий json_schema, как у остальных классификаторов.

Все функции safe-by-design: при недоступности модели/нет ключей/битом
изображении возвращают понятную строку/пусто, но НИКОГДА не роняют код и не
меняют поведение обычного поиска.
"""

from __future__ import annotations

import base64
import logging
import os

from pydantic import BaseModel

logger = logging.getLogger(__name__)

# Имя мультимодальной модели. Конфигурируется через YANDEX_MULTIMODAL_MODEL
# (дефолт — qwen3.6-35b-a3b, доступна в синхронном API; см. GET /models).
MULTIMODAL_MODEL = os.environ.get("YANDEX_MULTIMODAL_MODEL") or "qwen3.6-35b-a3b"

# Максимальный размер изображения (в байтах) — защита от гигантского файла.
MAX_IMAGE_BYTES = 10 * 1024 * 1024

# Достаточно большой лимит токенов ответа — reasoning-модель тратит токены на
# внутреннее "размышление", без запаса ответ обрывался (finish_reason=length,
# JSON получался обрезанным — "Mapei Plasticheal" распознавался, но парсинг падал
# на EOF). 4000 с запасом, чтобы строгий JSON успевал завершиться.
_MULTIMODAL_MAX_TOKENS = 4000


class PhotoQueryGuess(BaseModel):
    """Схема ответа мультимодальной модели для поиска по фото.

    Все поля обязательны (required): Yandex strict-json_schema требует
    additionalProperties=False и все поля required (дефолты делают поле optional
    и модель отвечает "Invalid JSON Schema"). Пустая строка допустима.

    keywords — короткое поисковое ядро (что реально искать в каталоге товаров).
    used_text — текст, который удалось прочитать на фото (может быть пустым —
                учёт форм-фактора: надписей может не быть).
    """

    keywords: str
    used_text: str
    reasoning: str


def describe_product_from_image(
    image_bytes: bytes,
    mimetype: str,
    client=None,
    model: str | None = None,
) -> str:
    """Возвращает поисковое ядро (строку) по фотографии товара.

    Отправляет картинку (base64 image_url) в мультимодальную qwen3.6-35b-a3b
    через OpenAI-совместимый интерфейс Yandex AI Studio (тот же ключ/folder).
    Промпт явно просит описать ОБЪЕКТ и его форм-фактор, не только текст.

    Возвращает keywords; при недоступности модели/нет ключей/пустом ответе —
    пустую строку (вызывающий webapp покажет понятную ошибку).
    """
    if not image_bytes:
        logger.warning("photo_search: пустые данные изображения")
        return ""
    if len(image_bytes) > MAX_IMAGE_BYTES:
        logger.warning("photo_search: изображение больше %d байт", MAX_IMAGE_BYTES)
        return ""
    if not (mimetype and mimetype.startswith("image/")):
        logger.warning("photo_search: невалидный MIME-тип %r", mimetype)
        return ""

    try:
        from procurement_search.yandexgpt_classifier import _ask_image

        guess = _ask_image(
            system_prompt=(
                "Ты — помощник байера B2B-закупок. По фотографии товара/изделия/этикетки "
                "определи, что это за товар, и выдай КОРОТКОЕ поисковое ядро для "
                "поисковой системы (название + ключевые характеристики).\n"
                "ВАЖНО ПРО ФОРМ-ФАКТОР: текст на фото может отсутствовать. Если надписей "
                "нет — опиши сам объект по внешнему виду: форма, геометрия, материал, "
                "цвет, конструктивные особенности, предполагаемое назначение. Из этого "
                "и собери поисковое ядро.\n"
                "Если текст на фото ЕСТЬ (название, маркировка, артикул, характеристики) — "
                "используй его как главный источник, но дополни/уточни по внешнему виду.\n"
                "Оставь в keywords только то, что реально искать в каталоге товаров; "
                "не добавляй цену, адреса, телефоны, служебное. Сохраняй значимые слова "
                "(бренды, числа с единицами) без искажения. В used_text верни дословно "
                "существенный распознанный текст (или пустую строку, если его нет). Если "
                "определить товар нельзя вовсе — верни keywords пустой строкой."
            ),
            prompt_text=(
                "Определи товар по этой фотографии и выдай поисковое ядро для каталога "
                "(учти, что текст может отсутствовать — описывай по форм-фактору)."
            ),
            image_bytes=image_bytes,
            mimetype=mimetype,
            output_model=PhotoQueryGuess,
            client=client,
            model=model,
            max_tokens=_MULTIMODAL_MAX_TOKENS,
        )
        return (guess.keywords or "").strip()
    except Exception as exc:  # noqa: BLE001 — модель недоступна, не роняем
        logger.warning("photo_search: мультимодальная модель не сработала: %s", exc)
        return ""