"""Слой 0 (доп.): сжатие длинного шаблонного запроса байера в короткое
поисковое ядро.

Проблема, которую решает: реальные запросы тестировщиков часто содержат
юридические вставки, ссылки на законы, цитаты статей, требования к лицензии
и канцелярит ("включая/кроме/далее", "обязательное наличие"). Если отдать
поисковику весь такой текст целиком, важные слова (регион, класс опасности,
название услуги) тонут в мусоре, и источник находит не то. Сжатие оставляет
только суть — что ищет байер + где + ключевые квалификаторы.

По образцу brand_extractor.py: открытый смысл (нельзя перечислить все формы
"юридической каши" заранее), поэтому только LLM-путь, gated тем же флагом
use_llm_fallback. Откат на текущее поведение безопасный и полный: при
выключенном флаге, недоступном LLM, ошибке или пустом результате — просто
возвращаем None, и pipeline работает как раньше.

Срабатывает только на ДЛИННЫХ запросах (KERNEL_MIN_LEN): короткие и так
понятны поисковику, сжимать незачем (и незачем тратить LLM).
"""

from __future__ import annotations

import logging

logger = logging.getLogger(__name__)

# Короче этого запрос сжимать незачем: и так понятен поисковику, а LLM-вызов
# не бесплатен. Порог взят с запасом под реальный пример про отходы (длинный
# юридический текст), но не трогающий обычные товарные запросы вида
# "смазочно-охлаждающая жидкость для вытяжки и штамповки металла 5 кг 3 штуки".
KERNEL_MIN_LEN = 60


def condense_query(raw_query: str, use_llm_fallback: bool = False) -> str | None:
    """Возвращает короткое поисковое ядро для длинного шаблонного запроса,
    или None, если сжимать нечего/незачем:

    - use_llm_fallback=False (по умолчанию) — не тратим LLM без явного
      включения (тот же принцип, что у остальных LLM-fallback шагов
      пайплайна);
    - запрос короче KERNEL_MIN_LEN — и так понятен, сжимать незачем;
    - LLM недоступна/упала, или вернула пустое ядро — работаем как раньше.

    Возвращает ТОЛЬКО kernel (строку), region отдельно не отдаём наружу —
    у него пока нет потребителя ниже по пайплайну (класс опасности/регион
    остаются просто словами ядра для ранжирования поисковика, жёсткая
    фильтрация по ним — отдельная будущая задача).
    """
    if not use_llm_fallback or len(raw_query) < KERNEL_MIN_LEN:
        return None

    try:
        from procurement_search.yandexgpt_classifier import (
            condense_query_with_yandexgpt as condense_fn,
        )
    except ImportError:
        logger.warning("Пакет openai не установлен — сжатие запроса пропущено")
        return None

    try:
        guess = condense_fn(raw_query)
    except Exception:
        logger.warning("Сжатие запроса %r не сработало", raw_query, exc_info=True)
        return None

    kernel = (guess.kernel or "").strip()
    if not kernel:
        logger.info("LLM не нашла, что сократить в запросе %r — работаем как раньше", raw_query)
        return None
    return kernel